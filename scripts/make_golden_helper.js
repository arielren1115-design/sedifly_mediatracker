// Generates scripts/golden_sheet_helper.gs: a one-off script to paste into the golden Google Sheet (Extensions, Apps Script).
// It adds a hover note to each column and dropdowns for the label columns. It lives in the sheet, not in the monitoring tool.
//   node scripts/make_golden_helper.js
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { parseCsv } from '../src/core/csv.js';
import { loadEntities } from '../src/core/entities.js';
import { loadRules, activeRules } from '../src/core/rules.js';
import { CATEGORIES, PRIORITIES, SOURCE_TYPES, SENTIMENTS, CHANNELS } from '../src/core/taxonomy.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const csv = (f) => parseCsv(readFileSync(path.join(root, 'fixtures/config', f), 'utf8'));
const entities = loadEntities(csv('entities.csv')).map((e) => e.name);
const rules = activeRules(loadRules(csv('rules.csv')));
const short = (t) => (t.length > 70 ? `${t.slice(0, 67)}...` : t);

const notes = {
  id: 'Short unique ID for this row, for example g001. Already filled in.',
  date_seen: 'For people only: when the item appeared. Not used by the test.',
  route: 'How the item reached the tool: Google Alerts, Talkwalker, F5Bot or Team forward. Already filled in.',
  alert_name: 'The name of the alert that found it, for example Sedifly or Joash Lee. Blank for team forwards.',
  url: 'The link. Already filled in.',
  title: 'The headline the tool would have seen. Blank for team forwards, because a forward carries no title.',
  snippet: 'The text around the mention that the tool would have seen. For a team forward, put the forwarder\'s comment here.',
  outlet: 'The publication, site or account name. Already filled in.',
  expected_entity: 'LABEL: who or what the item is about, picked from the list (Monitored Entities). Leave blank if the item is not about any of them.',
  expected_category: `LABEL: ${CATEGORIES.map((c) => `${c.value}: ${c.definition}`).join(' ')}`,
  expected_source_type: `LABEL: ${SOURCE_TYPES.map((c) => `${c.value}: ${c.definition}`).join(' ')}`,
  expected_channel: 'LABEL: where it appeared: News, Blog, Listing, Reddit, Hacker News, Forum, Social, Podcast or Other. Optional; leave blank if unsure, blank columns are not checked.',
  expected_priority: `LABEL: ${PRIORITIES.map((c) => `${c.value}: ${c.definition}`).join(' ')}`,
  expected_sentiment: 'LABEL: Positive, Neutral, Negative or Unclear. Optional; blank is not checked.',
  expected_rule_ids: `LABEL: the Monitoring Rule IDs that apply, separated by commas, for example MR-006, MR-007. Optional; blank is not checked. Active rules: ${rules.map((r) => `${r.id} (${r.route}: ${short(r.trigger)})`).join('; ')}`,
  expected_outcome: 'REQUIRED. What the tool should do: coverage (log it as a row), review (a person should look, for example a different person with the same name or an unclear item) or skip (not relevant, ignore it). A row without this is ignored by the test.',
  notes: 'For people only: reasons, questions for Ben. Not used by the test.',
};
const lists = {
  expected_entity: { values: entities, strict: false },
  expected_category: { values: CATEGORIES.map((c) => c.value), strict: true },
  expected_source_type: { values: SOURCE_TYPES.map((c) => c.value), strict: true },
  expected_channel: { values: CHANNELS, strict: true },
  expected_priority: { values: PRIORITIES.map((c) => c.value), strict: true },
  expected_sentiment: { values: SENTIMENTS, strict: true },
  expected_outcome: { values: ['coverage', 'review', 'skip'], strict: true },
};

const gs = `// Paste into the golden Google Sheet: Extensions, Apps Script. Save, choose prepareGoldenSheet, Run, and approve the permissions.
// It only adds hover notes to the header row and dropdowns to the label columns. It does not change any of your values.
// Generated by scripts/make_golden_helper.js from the repo's taxonomy, entities and rules.

var NOTES = ${JSON.stringify(notes, null, 2)};

var LISTS = ${JSON.stringify(lists, null, 2)};

function prepareGoldenSheet() {
  var sheet = SpreadsheetApp.getActiveSpreadsheet().getSheets()[0];
  var headers = sheet.getRange(1, 1, 1, sheet.getLastColumn()).getValues()[0].map(function (h) { return String(h).trim(); });
  var rows = Math.max(sheet.getMaxRows() - 1, 1);
  var done = [];
  headers.forEach(function (name, i) {
    if (NOTES[name]) { sheet.getRange(1, i + 1).setNote(NOTES[name]); done.push(name); }
    if (LISTS[name]) {
      var rule = SpreadsheetApp.newDataValidation().requireValueInList(LISTS[name].values, true).setAllowInvalid(!LISTS[name].strict).build();
      sheet.getRange(2, i + 1, rows, 1).setDataValidation(rule);
    }
  });
  sheet.setFrozenRows(1);
  Logger.log('Notes added to: ' + done.join(', '));
}
`;
writeFileSync(path.join(root, 'scripts/golden_sheet_helper.gs'), gs);
console.log(`wrote scripts/golden_sheet_helper.gs (${gs.length} characters)`);
